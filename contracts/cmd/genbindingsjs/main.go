// Command genbindingsjs generates the TypeScript bindings npm package
// @chainlink/chainlink-canton-contracts from the released DARs.
//
// It runs `dpm codegen-js` over contracts/dars/released/*.dar with the npm
// scope set to the package name, so the generated cross-package imports
// (require('@chainlink/chainlink-canton-contracts/<package>')) resolve as
// deep imports of the single published package. The codegen output is then
// post-processed into the output directory (by default bindings/damljs):
//
//   - each generated package's lib/ contents are copied to <out>/<package>/
//     (flattened one level); the per-package package.json/tsconfig.json stubs
//     are dropped in favour of a single root package.json
//   - the root package.json is (re)written: the version comes from the
//     release-please manifest (contracts component) so the package stays in
//     lockstep with contracts/vX.X.X releases, and the dependency/peer
//     dependency requirements are extracted from the codegen stubs
//   - root index.js/index.d.ts barrels re-exporting every generated package
//
// README.md, LICENSE and node_modules in the output directory are
// hand-maintained (or local) and are left untouched; stale generated files
// are removed.
//
// Usage (from the contracts directory):
//
//	go run ./cmd/genbindingsjs [-dpm dpm] [-out bindings/damljs]
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/rs/zerolog"
	"github.com/rs/zerolog/log"
)

const (
	npmScope    = "chainlink/chainlink-canton-contracts"
	packageName = "@" + npmScope

	// releaseComponent is the release-please component whose version the
	// bindings package tracks (contracts/vX.X.X tags).
	releaseComponent = "contracts"

	description = "TypeScript bindings for the Chainlink Canton contracts, generated by `dpm codegen-js`"
)

// keepEntries are output-directory entries not managed by this command:
// hand-maintained documentation and local installs.
var keepEntries = map[string]bool{
	"README.md":    true,
	"LICENSE":      true,
	"node_modules": true,
}

// semverRe matches exact semantic versions like 3.7.1.
var semverRe = regexp.MustCompile(`^\d+\.\d+\.\d+$`)

// stubPackageJSON is the per-package manifest emitted by `dpm codegen-js`.
type stubPackageJSON struct {
	Name             string            `json:"name"`
	Version          string            `json:"version"`
	License          string            `json:"license"`
	Description      string            `json:"description"`
	Dependencies     map[string]string `json:"dependencies"`
	PeerDependencies map[string]string `json:"peerDependencies"`
}

// exportsEntry is a single exports-map condition set.
type exportsEntry struct {
	Types   string `json:"types"`
	Default string `json:"default"`
}

// repository is the repository field of the root package.json.
type repository struct {
	Type      string `json:"type"`
	URL       string `json:"url"`
	Directory string `json:"directory"`
}

// rootPackageJSON is the manifest of the generated npm package.
type rootPackageJSON struct {
	Name             string                  `json:"name"`
	Version          string                  `json:"version"`
	Description      string                  `json:"description"`
	License          string                  `json:"license"`
	Type             string                  `json:"type"`
	Main             string                  `json:"main"`
	Types            string                  `json:"types"`
	Exports          map[string]exportsEntry `json:"exports"`
	Files            []string                `json:"files"`
	Repository       repository              `json:"repository"`
	Dependencies     map[string]string       `json:"dependencies"`
	PeerDependencies map[string]string       `json:"peerDependencies"`
}

func main() {
	log.Logger = log.Output(zerolog.ConsoleWriter{Out: os.Stderr})

	dpmBin := flag.String("dpm", "dpm", "Path to the dpm binary")
	darsDir := flag.String("dars", "dars/released", "Directory containing the DARs to generate bindings for")
	outDir := flag.String("out", "bindings/damljs", "Output directory (relative to the contracts directory)")
	manifestPath := flag.String("manifest", "../.release-please-manifest.json", "release-please manifest holding the package version")
	flag.Parse()

	dars, err := filepath.Glob(filepath.Join(*darsDir, "*.dar"))
	if err != nil {
		log.Fatal().Err(err).Msg("Failed to list DARs")
	}
	if len(dars) == 0 {
		log.Fatal().Str("dir", *darsDir).Msg("No DARs found")
	}
	sort.Strings(dars)

	version, err := releaseVersion(*manifestPath)
	if err != nil {
		log.Fatal().Err(err).Msg("Failed to determine package version")
	}

	tmpDir, err := os.MkdirTemp("", "genbindingsjs-")
	if err != nil {
		log.Fatal().Err(err).Msg("Failed to create temporary directory")
	}
	defer os.RemoveAll(tmpDir)

	if err := runCodegen(*dpmBin, tmpDir, dars); err != nil {
		log.Fatal().Err(err).Msg("Failed to run dpm codegen-js")
	}

	packages, err := listCodegenPackages(tmpDir)
	if err != nil {
		log.Fatal().Err(err).Msg("Failed to list codegen packages")
	}
	deps, peerDeps, err := collectDeps(tmpDir, packages)
	if err != nil {
		log.Fatal().Err(err).Msg("Failed to collect dependencies from codegen stubs")
	}

	if err := rebuildOutput(*outDir, tmpDir, packages); err != nil {
		log.Fatal().Err(err).Msg("Failed to rebuild output directory")
	}
	if err := writeManifest(*outDir, version, deps, peerDeps); err != nil {
		log.Fatal().Err(err).Msg("Failed to write package.json")
	}
	if err := writeBarrels(*outDir, packages); err != nil {
		log.Fatal().Err(err).Msg("Failed to write index barrels")
	}

	log.Info().
		Int("packages", len(packages)).
		Str("version", version).
		Str("peerDependencies.@daml/types", peerDeps["@daml/types"]).
		Str("out", *outDir).
		Msg("Generated " + packageName)
}

// releaseVersion reads the version for the contracts component from the
// release-please manifest at the repository root.
func releaseVersion(manifestPath string) (string, error) {
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		return "", err
	}
	var manifest map[string]string
	if err := json.Unmarshal(data, &manifest); err != nil {
		return "", fmt.Errorf("failed to parse %s: %w", manifestPath, err)
	}
	version, ok := manifest[releaseComponent]
	if !ok || version == "" {
		return "", fmt.Errorf("no %q entry in %s", releaseComponent, manifestPath)
	}
	return version, nil
}

// runCodegen invokes `dpm codegen-js` on all DARs with the npm scope set to
// the package name.
func runCodegen(dpmBin, outDir string, dars []string) error {
	args := []string{"codegen-js", "-o", outDir, "-s", npmScope}
	args = append(args, dars...)
	cmd := exec.Command(dpmBin, args...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%s %s: %w", dpmBin, strings.Join(args, " "), err)
	}
	return nil
}

// listCodegenPackages returns the sorted names of the packages generated by
// `dpm codegen-js` (directories containing a lib/ output).
func listCodegenPackages(codegenDir string) ([]string, error) {
	entries, err := os.ReadDir(codegenDir)
	if err != nil {
		return nil, err
	}
	var packages []string
	for _, entry := range entries {
		if entry.IsDir() && dirExists(filepath.Join(codegenDir, entry.Name(), "lib")) {
			packages = append(packages, entry.Name())
		}
	}
	sort.Strings(packages)
	return packages, nil
}

// collectDeps extracts the runtime dependencies and peer dependencies every
// generated package agrees on. Cross-package references (file: specifiers)
// are dropped: they resolve as deep imports of the generated package itself.
// The codegen stubs pin @daml/types to the exact SDK version, which is not
// necessarily published (e.g. 3.7.1 was skipped); peer dependencies are
// therefore widened to caret ranges.
func collectDeps(codegenDir string, packages []string) (deps, peers map[string]string, err error) {
	deps, peers = map[string]string{}, map[string]string{}
	for _, pkg := range packages {
		data, err := os.ReadFile(filepath.Join(codegenDir, pkg, "package.json"))
		if err != nil {
			return nil, nil, err
		}
		var stub stubPackageJSON
		if err := json.Unmarshal(data, &stub); err != nil {
			return nil, nil, fmt.Errorf("failed to parse stub package.json of %s: %w", pkg, err)
		}
		if err := mergeDeps(deps, stub.Dependencies, pkg); err != nil {
			return nil, nil, err
		}
		if err := mergeDeps(peers, caretRanges(stub.PeerDependencies), pkg); err != nil {
			return nil, nil, err
		}
	}
	return deps, peers, nil
}

// caretRanges widens exact versions to caret ranges.
func caretRanges(deps map[string]string) map[string]string {
	out := make(map[string]string, len(deps))
	for name, spec := range deps {
		if semverRe.MatchString(spec) {
			spec = "^" + spec
		}
		out[name] = spec
	}
	return out
}

func mergeDeps(into, from map[string]string, pkg string) error {
	for name, spec := range from {
		if strings.HasPrefix(spec, "file:") {
			continue
		}
		if prev, ok := into[name]; ok && prev != spec {
			return fmt.Errorf("%s requires %s@%s but another package requires %s", pkg, name, spec, prev)
		}
		into[name] = spec
	}
	return nil
}

// rebuildOutput replaces everything managed by this command in outDir with
// the post-processed codegen output.
func rebuildOutput(outDir, codegenDir string, packages []string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(outDir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if keepEntries[entry.Name()] {
			continue
		}
		if err := os.RemoveAll(filepath.Join(outDir, entry.Name())); err != nil {
			return err
		}
	}
	for _, pkg := range packages {
		libDir := filepath.Join(codegenDir, pkg, "lib")
		if err := copyTree(libDir, filepath.Join(outDir, pkg)); err != nil {
			return fmt.Errorf("failed to copy %s: %w", libDir, err)
		}
	}
	return nil
}

// copyTree copies the file tree rooted at src into dst.
func copyTree(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, 0o644)
	})
}

// writeManifest writes the root package.json of the generated package.
func writeManifest(outDir, version string, deps, peers map[string]string) error {
	manifest := rootPackageJSON{
		Name:        packageName,
		Version:     version,
		Description: description,
		License:     "BUSL-1.1",
		Type:        "commonjs",
		Main:        "index.js",
		Types:       "index.d.ts",
		Exports: map[string]exportsEntry{
			".":   {Types: "./index.d.ts", Default: "./index.js"},
			"./*": {Types: "./*/index.d.ts", Default: "./*/index.js"},
		},
		Files:            []string{"*"},
		Repository:       repository{Type: "git", URL: "git+https://github.com/smartcontractkit/chainlink-canton.git", Directory: "contracts/bindings/damljs"},
		Dependencies:     deps,
		PeerDependencies: peers,
	}
	// Serialize exactly like release-please re-serializes JSON files when
	// bumping the version (2-space indent, no HTML escaping, trailing
	// newline), so the version bump in the release pull request is the only
	// diff.
	var buf bytes.Buffer
	encoder := json.NewEncoder(&buf)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(manifest); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "package.json"), buf.Bytes(), 0o644)
}

// writeBarrels writes root index.js/index.d.ts re-exporting every generated
// package under its directory name.
func writeBarrels(outDir string, packages []string) error {
	if len(packages) == 0 {
		return nil
	}
	var js, dts strings.Builder
	js.WriteString("// Generated by contracts/cmd/genbindingsjs — do not edit.\n\n\"use strict\";\n\nmodule.exports = {\n")
	dts.WriteString("// Generated by contracts/cmd/genbindingsjs — do not edit.\n\ndeclare const packages: {\n")
	for _, pkg := range packages {
		fmt.Fprintf(&js, "    '%s': require('./%s'),\n", pkg, pkg)
		fmt.Fprintf(&dts, "    readonly '%s': typeof import('./%s');\n", pkg, pkg)
	}
	js.WriteString("};\n")
	dts.WriteString("};\n\nexport = packages;\n")

	if err := os.WriteFile(filepath.Join(outDir, "index.js"), []byte(js.String()), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "index.d.ts"), []byte(dts.String()), 0o644)
}

func dirExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}
